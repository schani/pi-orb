type Command = keyof typeof commands;
function isCommand(value: string): value is Command {
  return Object.hasOwn(commands, value);
}

function commandHelp(command: Command): string {
  const { usage, summary, details, examples } = commands[command];
  return [
    `usage: ${usage.replaceAll("\n", "\n       ")}`,
    "",
    summary,
    ...details,
    ...(examples.length > 0 ? ["", "Examples:", ...examples.map((example) => `  ${example}`)] : []),
    "",
  ].join("\n");
}

const ROOT_USAGE = "usage: pi-orb <command> [arguments]";

function invalidUsage(): string {
  return [
    ROOT_USAGE,
    ...Object.values(commands).map(({ usage }) => `  ${usage.replaceAll("\n", "\n  ")}`),
    "Run pi-orb --help for the full reference, or pi-orb help <command>.",
    "",
  ].join("\n");
}

export function rootHelp(): string {
  return [
    ROOT_USAGE,
    "  pi-orb help [command]",
    "  pi-orb <command> --help",
    "",
    "Use --help or -h alone, or immediately after a command, for help.",
    "Command-leading help ignores remaining arguments; later help-like argument data is not intercepted.",
    "Help needs no orb environment and makes no runtime requests. Commands require runtime identity.",
    "Only id-token supports --flag=value; other options use separate arguments. No generic -- terminator.",
    "Errors go to stderr; command output goes to stdout. Invalid usage/help exits 2; help exits 0.",
    "",
    ...(Object.keys(commands) as Command[]).map(commandHelp),
  ].join("\n");
}

type HelpFailure = { readonly type: "invalid_help"; readonly message: string };

export function parseHelpArgs(args: readonly string[]): Result<string, HelpFailure> {
  const [first, second] = args;
  if (args.length === 1 && (first === "help" || first === "--help" || first === "-h"))
    return ok(rootHelp());
  const command =
    args.length === 2 && first === "help"
      ? second
      : args.length >= 2 && (second === "--help" || second === "-h")
        ? first
        : undefined;
  if (command !== undefined && isCommand(command)) return ok(commandHelp(command));
  return err({ type: "invalid_help", message: invalidUsage() });
}
