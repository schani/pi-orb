const code = (
  owner: NonNullable<Extract<ExtractionSelector, { kind: "code" }>["owner"]>,
  node: "string" | "template" | "joined-array" = "string",
  extra: Partial<Extract<ExtractionSelector, { kind: "code" }>> = {},
): ExtractionSelector => ({ kind: "code", owner, node, ...extra });
const variable = (
  name: string,
  node: "string" | "template" | "joined-array" = "string",
  extra: Partial<Extract<ExtractionSelector, { kind: "code" }>> = {},
) => code({ kind: "variable", name }, node, extra);
const fn = (
  name: string,
  node: "string" | "template" | "joined-array" = "string",
  extra: Partial<Extract<ExtractionSelector, { kind: "code" }>> = {},
) => code({ kind: "function", name }, node, extra);
const prompt = (
  id: string,
  title: string,
  category: string,
  scope: string,
  path: string,
  selector: ExtractionSelector,
  note?: string,
): Definition => ({
  id,
  title,
  category,
  scope,
  path,
  selector,
  editable: true,
  ...(note ? { note } : {}),
});
const installed = (
  id: string,
  title: string,
  pkg: string,
  path: string,
  selector: ExtractionSelector,
  note?: string,
): Definition => ({
  ...prompt(
    `upstream/${id}`,
    title,
    "Upstream",
    rootChild,
    `node_modules/${pkg}/${path}`,
    selector,
  ),
  editable: false,
  packagePath: `node_modules/${pkg}/package.json`,
  note: `Installed upstream prompt; read-only.${note ? ` ${note}` : ""}`,
});
const unavailable = (id: string, title: string, scope: string, note: string): Definition => ({
  id: `dynamic/${id}`,
  title,
  category: "Dynamic",
  scope,
  path: "",
  content: "",
  editable: false,
  note: `Content unavailable in this checkout. ${note}`,
});

